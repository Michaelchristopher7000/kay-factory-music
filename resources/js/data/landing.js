export function getArtistBySlug(slug) {
    return ARTISTS.find((a) => a.slug === slug) || null;
}

export function getReleaseBySlug(slug) {
    return RELEASES.find((r) => r.slug === slug) || null;
}

export function getReleasesByArtistSlug(slug) {
    return RELEASES.filter((r) => r.artistSlug === slug);
}

